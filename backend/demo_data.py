"""Single source of truth for the demo e-commerce dataset: table definitions, deterministic rows and T-SQL DDL.

`data/schema.sql` is generated from SCHEMA, `data/seed_azure.py` loads generate() into Azure SQL, and the in-memory test
double loads the same rows, so the three can never drift apart.
"""
import random
from dataclasses import dataclass
from datetime import date, timedelta
from typing import Optional


@dataclass(frozen=True)
class Column:
    name: str
    sql_type: str
    primary_key: bool = False
    references: Optional[str] = None
    nullable: bool = True
    check: Optional[str] = None
    default: Optional[str] = None


@dataclass(frozen=True)
class Table:
    name: str
    columns: tuple[Column, ...]


def _pk(name: str) -> Column:
    return Column(name, "INT", primary_key=True, nullable=False)


SCHEMA: tuple[Table, ...] = (
    Table("customers", (
        _pk("customer_id"), Column("name", "NVARCHAR(200)", nullable=False), Column("email", "NVARCHAR(200)"),
        Column("city", "NVARCHAR(100)"), Column("signup_date", "DATE"),
        Column("description", "NVARCHAR(MAX)", default="End customer who places orders"))),
    Table("products", (
        _pk("product_id"), Column("name", "NVARCHAR(200)", nullable=False), Column("category", "NVARCHAR(100)"),
        Column("price", "FLOAT"), Column("stock_quantity", "INT"), Column("created_at", "DATE"))),
    Table("orders", (
        _pk("order_id"), Column("customer_id", "INT", references="customers.customer_id"),
        Column("order_date", "DATE", nullable=False), Column("total_amount", "FLOAT"), Column("status", "NVARCHAR(50)"),
        Column("shipping_date", "DATE"))),
    Table("order_items", (
        _pk("item_id"), Column("order_id", "INT", references="orders.order_id"),
        Column("product_id", "INT", references="products.product_id"), Column("quantity", "INT"),
        Column("unit_price", "FLOAT"), Column("discount", "FLOAT"))),
    Table("payments", (
        _pk("payment_id"), Column("order_id", "INT", references="orders.order_id"), Column("amount", "FLOAT"),
        Column("payment_method", "NVARCHAR(50)"), Column("payment_date", "DATE"), Column("status", "NVARCHAR(50)"))),
    Table("reviews", (
        _pk("review_id"), Column("product_id", "INT", references="products.product_id"),
        Column("customer_id", "INT", references="customers.customer_id"),
        Column("rating", "INT", check="rating BETWEEN 1 AND 5"), Column("review_text", "NVARCHAR(MAX)"),
        Column("review_date", "DATE"))),
)

TABLE_NAMES = tuple(t.name for t in SCHEMA)
ROW_COUNTS = {"customers": 1000, "products": 200, "orders": 5000, "order_items": 15000, "payments": 5000, "reviews": 3000}


def base_type(sql_type: str) -> str:
    return sql_type.split("(")[0].upper()


def tsql_statements() -> list[str]:
    stmts = [f"DROP TABLE IF EXISTS dbo.{t.name}" for t in reversed(SCHEMA)]
    for t in SCHEMA:
        lines = []
        for c in t.columns:
            line = f"    {c.name} {c.sql_type} {'NOT NULL' if not c.nullable else 'NULL'}"
            if c.default is not None:
                line += f" DEFAULT '{c.default}'"
            lines.append(line)
        pks = [c.name for c in t.columns if c.primary_key]
        lines.append(f"    CONSTRAINT pk_{t.name} PRIMARY KEY ({', '.join(pks)})")
        for c in t.columns:
            if c.references:
                ref_table, ref_col = c.references.split(".")
                lines.append(f"    CONSTRAINT fk_{t.name}_{c.name} FOREIGN KEY ({c.name}) REFERENCES dbo.{ref_table}({ref_col})")
            if c.check:
                lines.append(f"    CONSTRAINT ck_{t.name}_{c.name} CHECK ({c.check})")
        stmts.append(f"CREATE TABLE dbo.{t.name} (\n" + ",\n".join(lines) + "\n)")
    return stmts


def tsql_ddl() -> str:
    header = ("-- QueryMind demo schema (T-SQL / Azure SQL). GENERATED by `python data/seed_azure.py --write-schema`\n"
              "-- from backend/demo_data.py; do not edit by hand. Statements are separated by semicolons.\n")
    return header + ";\n\n".join(tsql_statements()) + ";\n"


FIRST_NAMES = ["Aarav", "Siya", "Rohan", "Ananya", "Vikram", "Priya", "Arjun", "Neha", "Suresh", "Kiran", "Meera", "John", "Sarah",
               "David", "Emma", "Raj", "Pooja", "Amit", "Lisa", "Mike"]
LAST_NAMES = ["Sharma", "Patel", "Singh", "Kumar", "Gupta", "Reddy", "Nair", "Shah", "Verma", "Mehta", "Smith", "Jones", "Brown",
              "Davis", "Wilson"]
CITIES = ["Mumbai", "Delhi", "Bangalore", "Hyderabad", "Chennai", "Pune", "Kolkata", "Jaipur", "Ahmedabad", "Surat", "New York",
          "London"]
CATEGORIES = ["Electronics", "Apparel", "Home", "Sports", "Books"]
PRODUCT_BASE = ["Widget", "Gadget", "Tool", "Device", "Gear", "Kit", "Pack", "Box"]
PRODUCT_SUFFIX = ["Pro", "Max", "Lite", "Ultra", "Plus", "Mini"]
PAYMENT_METHODS = ["credit_card", "paypal", "upi", "net_banking"]
ORDER_STATUSES = ["completed", "pending", "cancelled"]
PAYMENT_STATUSES = ["success", "failed", "refunded"]
REVIEW_WORDS = ["great", "good", "average", "excellent", "poor"]


def generate(seed: int = 42, today: Optional[date] = None) -> dict[str, list[tuple]]:
    rng = random.Random(seed)
    today = today or date.today()

    def rand_date(days_back: int = 365) -> date:
        return today - timedelta(days=rng.randint(0, days_back))

    customers = []
    for i in range(1, 1001):
        name = f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}"
        email = f"{name.lower().replace(' ', '.')}{i}@example.com"
        customers.append((i, name, email, rng.choice(CITIES), rand_date(730), "End customer who places orders"))

    products = []
    for i in range(1, 201):
        pname = f"{rng.choice(PRODUCT_BASE)} {rng.choice(PRODUCT_SUFFIX)} {i}"
        products.append((i, pname, rng.choice(CATEGORIES), round(rng.uniform(10, 1000), 2), rng.randint(0, 500), rand_date(365)))

    orders = []
    for i in range(1, 5001):
        cust = rng.randint(1, 1000)
        o_date = rand_date(365)
        s_date = o_date + timedelta(days=rng.randint(1, 7))
        orders.append((i, cust, o_date, round(rng.uniform(20, 2000), 2), rng.choice(ORDER_STATUSES), s_date))

    price_of = {p[0]: p[3] for p in products}
    items = []
    for i in range(1, 15001):
        oid, pid, qty = rng.randint(1, 5000), rng.randint(1, 200), rng.randint(1, 5)
        items.append((i, oid, pid, qty, price_of[pid], round(rng.uniform(0, 0.2), 2)))

    payments = []
    for i in range(1, 5001):
        amount = orders[i - 1][3]
        if rng.random() < 0.1:
            amount = round(amount * 0.9, 2)
        payments.append((i, i, amount, rng.choice(PAYMENT_METHODS), rand_date(365), rng.choice(PAYMENT_STATUSES)))

    reviews = []
    for i in range(1, 3001):
        reviews.append((i, rng.randint(1, 200), rng.randint(1, 1000), rng.randint(1, 5),
                        f"This product is {rng.choice(REVIEW_WORDS)}.", rand_date(365)))

    return {"customers": customers, "products": products, "orders": orders, "order_items": items, "payments": payments,
            "reviews": reviews}
