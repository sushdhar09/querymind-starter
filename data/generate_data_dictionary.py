"""Generate docs/DATA_DICTIONARY.md from the live schema, foreign keys, column metadata and sample values.

    python data/generate_data_dictionary.py [--db PATH] [--out PATH]
"""
import argparse
import json
import os
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE_NOTES = {
    "customers": "People who place orders.",
    "products": "Items in the catalog.",
    "orders": "One row per customer order (header level).",
    "order_items": "Line items: which products, how many and at what price are on each order.",
    "payments": "Payment attempts recorded against orders.",
    "reviews": "Customer ratings and comments for products.",
}
INTERNAL = {"query_logs", "few_shot_examples", "schema_descriptions"}
ENUM_LIMIT = 12


def default_db() -> Path:
    env = os.environ.get("DB_PATH")
    if env:
        return Path(env) if Path(env).is_absolute() else ROOT / env
    return ROOT / "data" / "querymind.db"


def build(db: Path) -> str:
    meta = json.loads((ROOT / "data" / "column_metadata.json").read_text(encoding="utf-8"))
    conn = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
    tables = [r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid")
              if r[0] not in INTERNAL]
    out = ["# Data dictionary", "",
           "Generated by `python data/generate_data_dictionary.py` from the database schema and `data/column_metadata.json`. "
           "Do not edit by hand; edit the metadata and regenerate.", "",
           "Domain: a synthetic e-commerce store (SQLite). Dates are stored as ISO text (`YYYY-MM-DD`) and were generated relative to the "
           "day the database was seeded, so use `date('now', ...)` in queries rather than fixed dates.", "", "## Tables", "",
           "| Table | Rows | Purpose |", "|---|---|---|"]
    for t in tables:
        out.append(f"| `{t}` | {conn.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0]} | {TABLE_NOTES.get(t, '')} |")

    out += ["", "## Relationships", ""]
    for t in tables:
        for r in conn.execute(f'PRAGMA foreign_key_list("{t}")'):
            out.append(f"- `{t}.{r[3]}` references `{r[2]}.{r[4]}`")
    out += ["- Many-to-many: `orders` and `products` are linked through `order_items`."]

    date_cols = []
    for t in tables:
        out += ["", f"## `{t}`", "", TABLE_NOTES.get(t, ""), "", "| Column | Type | Key | Description | Also called | Values |", "|---|---|---|---|---|---|"]
        fks = {r[3] for r in conn.execute(f'PRAGMA foreign_key_list("{t}")')}
        for _, name, ctype, _, _, pk in conn.execute(f'PRAGMA table_info("{t}")'):
            m = meta.get(t, {}).get(name, {})
            key = "PK" if pk else ("FK" if name in fks else "")
            values = ""
            if (ctype or "TEXT").upper() in ("TEXT", "VARCHAR") and not pk and not name.endswith("_id"):
                distinct = [r[0] for r in conn.execute(f'SELECT DISTINCT "{name}" FROM "{t}" WHERE "{name}" IS NOT NULL LIMIT {ENUM_LIMIT + 1}')]
                if 0 < len(distinct) <= ENUM_LIMIT:
                    values = ", ".join(f"`{v}`" for v in sorted(map(str, distinct)))
            if (ctype or "").upper() == "DATE":
                date_cols.append(f"`{t}.{name}`")
            out.append(f"| `{name}` | {ctype} | {key} | {m.get('description', '')} | {', '.join(m.get('synonyms', []))} | {values} |")

    out += ["", "## Date and time fields", "", "Use these for temporal questions: " + ", ".join(date_cols) + ".",
            "", "## Known ambiguities", "",
            "- **Revenue.** `orders.total_amount` is the value of the order at checkout; `payments.amount` is what the payment gateway actually "
            "captured and can differ because of refunds. Both list \"revenue\" as a synonym, so a question that only says \"revenue\" is ambiguous. "
            "The linker reports the ambiguity and the chat UI asks which one is meant; naming a table (\"revenue from payments\") resolves it.",
            "- **Status.** `orders.status` and `payments.status` use different value sets (see above); mention the table or one of its values.",
            "- **Name.** `customers.name` and `products.name` share a column name; mention customers or products.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", type=Path, default=default_db())
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "DATA_DICTIONARY.md")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(args.db), encoding="utf-8", newline="\n")
    print(f"Wrote {args.out}")
