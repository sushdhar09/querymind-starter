"""Generate docs/DATA_DICTIONARY.md from the database schema, foreign keys, column metadata and sample values.

    python data/generate_data_dictionary.py [--database memory|azure] [--out PATH]

`memory` (default) documents the demo dataset through the in-memory test double, so the output is reproducible; `azure`
reads your Azure SQL database (AZURE_SQL_CONNECTION_STRING) and is read-only.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.config import AZURE_SQL_CONNECTION_STRING  # noqa: E402
from backend.db import AnalyticsDatabase  # noqa: E402
from backend.factory import build_database  # noqa: E402

TABLE_NOTES = {
    "customers": "People who place orders.",
    "products": "Items in the catalog.",
    "orders": "One row per customer order (header level).",
    "order_items": "Line items: which products, how many and at what price are on each order.",
    "payments": "Payment attempts recorded against orders.",
    "reviews": "Customer ratings and comments for products.",
}
INTERNAL = {"query_logs", "few_shot_examples", "schema_descriptions"}
ENUM_LIMIT = 12


def build(database: AnalyticsDatabase) -> str:
    meta = json.loads((ROOT / "data" / "column_metadata.json").read_text(encoding="utf-8"))
    schema = database.load_schema()
    tables = [t for t in schema.tables if t not in INTERNAL]
    out = ["# Data dictionary", "",
           "Generated by `python data/generate_data_dictionary.py` from the database schema and `data/column_metadata.json`. "
           "Do not edit by hand; edit the metadata and regenerate.", "",
           "Domain: a synthetic e-commerce store on Azure SQL (T-SQL). Dates are `DATE` columns generated relative to the "
           "day the database was seeded, so write temporal queries relative to today (`DATEADD(DAY, -30, CAST(GETDATE() AS DATE))`) "
           "rather than with fixed dates.", "", "## Tables", "",
           "| Table | Rows | Purpose |", "|---|---|---|"]
    for t in tables:
        count = database.query(f"SELECT COUNT(*) AS n FROM {t}", 1, 30).rows[0][0]
        out.append(f"| `{t}` | {count} | {TABLE_NOTES.get(t, '')} |")

    out += ["", "## Relationships", ""]
    for t, column, ref_table, ref_column in schema.foreign_keys:
        if t in tables:
            out.append(f"- `{t}.{column}` references `{ref_table}.{ref_column}`")
    out += ["- Many-to-many: `orders` and `products` are linked through `order_items`."]

    date_cols = []
    for t in tables:
        out += ["", f"## `{t}`", "", TABLE_NOTES.get(t, ""), "", "| Column | Type | Key | Description | Also called | Values |", "|---|---|---|---|---|---|"]
        fks = {c for ft, c, _, _ in schema.foreign_keys if ft == t}
        for column in schema.tables[t]:
            name, ctype = column.name, column.type
            m = meta.get(t, {}).get(name, {})
            pk = name in schema.primary_keys.get(t, set())
            key = "PK" if pk else ("FK" if name in fks else "")
            values = ""
            if "CHAR" in ctype.upper() and not pk and not name.endswith("_id"):
                distinct = database.sample_values(t, name, ENUM_LIMIT + 1)
                if 0 < len(distinct) <= ENUM_LIMIT:
                    values = ", ".join(f"`{v}`" for v in sorted(map(str, distinct)))
            if ctype.upper() == "DATE":
                date_cols.append(f"`{t}.{name}`")
            out.append(f"| `{name}` | {ctype} | {key} | {m.get('description', '')} | {', '.join(m.get('synonyms', []))} | {values} |")

    out += ["", "## Date and time fields", "", "Use these for temporal questions: " + ", ".join(date_cols) + ".",
            "", "## Known ambiguities", "",
            "- **Revenue.** `orders.total_amount` is the value of the order at checkout; `payments.amount` is what the payment gateway actually "
            "captured and can differ because of refunds. Both list \"revenue\" as a synonym, so a question that only says \"revenue\" is ambiguous. "
            "The linker reports the ambiguity and the chat UI asks which one is meant; naming a table (\"revenue from payments\") resolves it.",
            "- **Status.** `orders.status` and `payments.status` use different value sets (see above); mention the table or one of its values.",
            "- **Name.** `customers.name` and `products.name` share a column name; mention customers or products.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--database", default="memory", choices=["memory", "azure"])
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "DATA_DICTIONARY.md")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(build_database(args.database, AZURE_SQL_CONNECTION_STRING)), encoding="utf-8", newline="\n")
    print(f"Wrote {args.out}")
